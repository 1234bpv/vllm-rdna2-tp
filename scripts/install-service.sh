#!/usr/bin/env bash
# Prints a systemd unit that runs one preset's server in the foreground, with the
# commands that install it as comments at the top.
#
# Usage: install-service.sh PRESET [serve.sh options] [-- extra vLLM arguments]
#
# Nothing is installed or started: the unit goes to stdout, so it can be reviewed
# and saved. Installing it needs root; the printed commands are for you to run.
#
# Exit: 0 unit printed; 2 bad call, or serve.sh rejects the options.
set -uo pipefail
. "$(dirname "$(readlink -f "$0")")/lib.sh"

SERVE=$RR_RELEASE_DIR/serve.sh

usage() {
    cat <<'EOF'
Usage: install-service.sh PRESET [serve.sh options] [-- extra vLLM arguments]

Prints a systemd unit vllm-rdna2-PRESET.service that runs serve.sh PRESET
--foreground with the given options, and the commands that install it. Nothing is
installed. Options are passed to serve.sh; --print-command, --list, --help and
--foreground are not accepted here.
EOF
}

# unit_word ARG: one word of a systemd command line, in double quotes. A backslash
# and a double quote are escaped; $ and % are doubled so that systemd does not
# expand them.
unit_word() {
    local s=$1
    s=${s//\\/\\\\}
    s=${s//\"/\\\"}
    s=${s//\$/\$\$}
    s=${s//%/%%}
    printf '"%s"' "$s"
}

case ${1:-} in
    -h|--help)
        usage
        exit 0
        ;;
    "")
        rr_error "PRESET is required (see --help)"
        exit 2
        ;;
    -*)
        rr_error "PRESET must come first: install-service.sh PRESET [options] (see --help)"
        exit 2
        ;;
esac
PRESET=$1
shift
PARAMS=("$@")

for p in "${PARAMS[@]}"; do
    case $p in
        --print-command|--list|-h|--help|--foreground)
            rr_error "$p is not accepted here (see --help)"
            exit 2
            ;;
    esac
done

rr_preset_load "$PRESET" || exit 2

# serve.sh validates the preset and the options; --print-command checks them
# without starting anything or requiring the installation.
if ! timeout 60 "$SERVE" "$PRESET" --print-command "${PARAMS[@]}" >/dev/null; then
    rr_error "serve.sh rejects these options for preset $PRESET (see the message above)"
    exit 2
fi

USER_NAME=${USER:-}
if [ -z "$USER_NAME" ]; then
    USER_NAME=$(timeout 10 id -un 2>/dev/null)
fi
if [ -z "$USER_NAME" ]; then
    rr_error "cannot determine the user name: set USER and run again"
    exit 2
fi

UNIT=vllm-rdna2-$PRESET.service
exec_start="$(unit_word "$SERVE") $(unit_word "$PRESET") --foreground"
for p in "${PARAMS[@]}"; do
    exec_start+=" $(unit_word "$p")"
done

cat <<EOF
# $UNIT
# Generated by scripts/install-service.sh (release $RR_VERSION). Nothing was installed.
#
# Install (as root; read the unit first):
#   sudo install -m 0644 $UNIT /etc/systemd/system/$UNIT
#   sudo systemctl daemon-reload
#   sudo systemctl enable --now $UNIT
# Logs:  journalctl -u $UNIT -f
# Stop:  sudo systemctl stop $UNIT
# Exit codes 2, 3, 4 and 6 are not restarted (bad call, not installed, driver probe
# failed, previous server not stopped): a person must look at those first.

[Unit]
Description=vLLM on RDNA2 cards, preset $PRESET
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=3600
StartLimitBurst=2

[Service]
Type=simple
User=$USER_NAME
SupplementaryGroups=video render
Environment=$(unit_word "VLLM_RDNA2_HOME=$RR_HOME")
Environment=$(unit_word "ROCM_PATH=$RR_ROCM_PATH")
ExecStart=$exec_start
ExecStop=$(unit_word "$RR_RELEASE_DIR/stop.sh")
Restart=on-failure
RestartSec=60
RestartPreventExitStatus=2 3 4 6
KillSignal=SIGTERM
SendSIGKILL=no
TimeoutStopSec=120

[Install]
WantedBy=multi-user.target
EOF
exit 0
